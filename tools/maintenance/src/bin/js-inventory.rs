//! Inventory the handwritten JS boundary and the generated Worker JS artifact.
//! This native audit intentionally does not replace the real Wasm/Node tests.
use std::env;
use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Debug)]
struct SourceFile {
    path: String,
    bytes: u64,
    lines: usize,
}

fn gather(
    root: &Path,
    excluded_dirs: &[&str],
    extensions: &[&str],
) -> Result<Vec<SourceFile>, Box<dyn Error>> {
    let mut files = Vec::new();
    let mut pending = vec![root.to_path_buf()];
    while let Some(dir) = pending.pop() {
        for item in fs::read_dir(&dir)? {
            let item = item?;
            let kind = item.file_type()?;
            if kind.is_symlink() {
                continue;
            }
            let path = item.path();
            if kind.is_dir() {
                let name = item.file_name();
                if !excluded_dirs.iter().any(|excluded| name == *excluded) {
                    pending.push(path);
                }
                continue;
            }
            if !kind.is_file()
                || !path
                    .extension()
                    .and_then(|extension| extension.to_str())
                    .is_some_and(|extension| extensions.contains(&extension))
            {
                continue;
            }
            let bytes = fs::read(&path)?;
            let relative = path.strip_prefix(root)?;
            files.push(SourceFile {
                path: relative.to_string_lossy().replace('\\', "/"),
                bytes: bytes.len() as u64,
                lines: bytes.iter().filter(|&&byte| byte == b'\n').count()
                    + usize::from(!bytes.is_empty() && !bytes.ends_with(b"\n")),
            });
        }
    }
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(files)
}

fn check_handwritten(root: &Path) -> Result<(Vec<SourceFile>, usize), Box<dyn Error>> {
    // build/ is generated by worker-build; none of its JS is handwritten.
    let files = gather(
        root,
        &[".git", ".wrangler", "build", "target", "node_modules"],
        &["js", "mjs", "cjs", "jsx", "ts", "tsx", "py"],
    )?;
    let js: Vec<&str> = files
        .iter()
        .filter(|file| !file.path.ends_with(".py"))
        .map(|file| file.path.as_str())
        .collect();
    if js != ["tests/worker_runtime.mjs"] {
        return Err(format!("unexpected handwritten JavaScript/TypeScript: {js:?}").into());
    }
    let python: Vec<&str> = files
        .iter()
        .filter(|file| file.path.ends_with(".py"))
        .map(|file| file.path.as_str())
        .collect();
    if !python.is_empty() {
        return Err(format!("Python returned to the Rust-first repository: {python:?}").into());
    }

    let harness = fs::read_to_string(root.join("tests/worker_runtime.mjs"))?;
    let test_count = harness.matches("await test(").count();
    if test_count < 97 {
        return Err(format!("built-Wasm integration cases decreased: {test_count} < 97").into());
    }
    for marker in [
        "vm.SourceTextModule",
        "WebAssembly.Module",
        "vm.SyntheticModule",
        "class WorkerQueue",
        "class D1Database",
        "unauthenticated webhook is rejected",
        "queue failure prevents the webhook",
        "group A administrator cannot execute",
        "warning management is isolated",
        "post-delete count failure is a partial result",
        "old enforcement result after stop",
        "concurrent Cron claims cannot process",
    ] {
        if !harness.contains(marker) {
            return Err(format!("missing host-boundary coverage marker: {marker}").into());
        }
    }
    let workflow = fs::read_to_string(root.join(".github/workflows/build.yml"))?;
    if !workflow.contains("node --experimental-vm-modules tests/worker_runtime.mjs") {
        return Err("CI must run the real built-Wasm integration suite".into());
    }
    Ok((files, test_count))
}

fn main() -> Result<(), Box<dyn Error>> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let (handwritten, tests) = check_handwritten(&root)?;
    println!("Handwritten JS/TS files: {}", handwritten.len());
    for file in &handwritten {
        println!("  {}: {} bytes, {} lines", file.path, file.bytes, file.lines);
    }
    println!("Python files: 0");
    println!("Built-Wasm host integration tests: {tests}");

    let output_arg = env::args_os().nth(1).unwrap_or_else(|| "build".into());
    let build = PathBuf::from(output_arg);
    let build = if build.is_absolute() { build } else { root.join(build) };
    for required in ["index.js", "index_bg.wasm"] {
        if !build.join(required).is_file() {
            return Err(format!("missing worker-build output: {required}").into());
        }
    }
    let generated = gather(&build, &[], &["js", "mjs", "cjs"])?;
    if generated.is_empty() {
        return Err("worker-build produced no JavaScript host glue".into());
    }
    println!("Generated JS files: {}", generated.len());
    for file in &generated {
        println!("  {}: {} bytes, {} lines", file.path, file.bytes, file.lines);
    }
    println!(
        "Generated JS total: {} bytes, {} lines",
        generated.iter().map(|file| file.bytes).sum::<u64>(),
        generated.iter().map(|file| file.lines).sum::<usize>(),
    );
    println!("Generated Wasm: {} bytes", fs::metadata(build.join("index_bg.wasm"))?.len());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn handwritten_boundary_and_built_wasm_coverage_are_preserved() {
        let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
        let (files, cases) = check_handwritten(&root).unwrap();
        assert_eq!(files.len(), 1);
        assert!(cases >= 97);
    }
}
